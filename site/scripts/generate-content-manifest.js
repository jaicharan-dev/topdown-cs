/**
 * Builds a canonical inventory of every doc page: src/data/contentManifest.json
 *
 * This is the single source of truth for "what does the site contain", used by
 * progress tracking, completion percentages and difficulty weighting. Every
 * page is keyed by its frontmatter `id`, which is stable across renames of the
 * title or the heading, unlike the URL.
 *
 * It also acts as a content linter: a page with a missing or duplicate `id`,
 * or an unrecognised difficulty, fails the build. That is deliberate. Progress
 * records point at these ids, so a silent gap here would mean a user's history
 * quietly detaching from the page it belongs to.
 *
 * Deliberately no timestamp in the output: the file is committed, and a
 * regenerated date would make it show up as modified after every `npm start`.
 * Same reasoning as generate-dsa-stats.js.
 */

const fs = require('fs');
const path = require('path');

const docsDir = path.resolve(__dirname, '../docs');
const outDir = path.resolve(__dirname, '../src/data');
const outFile = path.join(outDir, 'contentManifest.json');

const ROUTE_BASE = '/docs';

/** Difficulty weights. A harder page is worth more toward a rank. */
const POINTS = { easy: 1, medium: 2, hard: 3 };

/**
 * Human labels for the top-level blocks, matching the cards on the homepage
 * so the two never disagree. Anything not listed falls back to a title-cased
 * directory name.
 */
const BLOCK_LABELS = {
  'oop-essential': 'OOP Essential',
  'oop-additional': 'OOP Additional',
  'dbms-essential': 'DBMS Essential',
  'dbms-additional': 'DBMS Additional',
  'os-essential': 'OS Essentials',
  'os-additional': 'OS Additional',
  'os-problems': 'OS Problems',
  'cn-essential': 'CN Essential',
  'cn-additional': 'CN Additional',
  'cn-problems': 'CN Problems',
  'design-patterns': 'Design Patterns',
  'code-tracing': 'Code Tracing',
  'database-design': 'DB Design',
  dsa: 'DSA',
};

function titleCase(dirName) {
  return dirName
    .replace(/^\d+-/, '')
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

/** Every .md file under docs, as paths relative to docs/, forward-slashed. */
function walk(dir, acc = [], base = dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, acc, base);
    } else if (entry.name.endsWith('.md') || entry.name.endsWith('.mdx')) {
      acc.push(path.relative(base, full).split(path.sep).join('/'));
    }
  }
  return acc;
}

/** Minimal frontmatter reader: these files are generated by us, not arbitrary. */
function frontmatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!match) return {};
  const out = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(line);
    if (kv) out[kv[1]] = kv[2].trim().replace(/^["']|["']$/g, '');
  }
  return out;
}

/** `sidebar-medium` -> `medium`. */
function difficultyOf(sidebarClassName) {
  if (!sidebarClassName) return null;
  const m = /^sidebar-(easy|medium|hard)$/.exec(sidebarClassName.trim());
  return m ? m[1] : null;
}

/**
 * Docusaurus strips a leading number prefix from DIRECTORY names when it
 * builds a route, so `docs/dsa/9-trees/...` is served at `/docs/dsa/trees/...`.
 * The file name is a different matter: an explicit frontmatter `id` overrides
 * the last path segment, and ours keep their prefixes, so `4-crc-computation`
 * stays as written.
 *
 * The two patterns below are copied verbatim from Docusaurus so the rule does
 * not drift: plugin-content-docs/src/numberPrefix.ts. The first is a date and
 * version guard that skips stripping altogether, which is why `16-1d-dp` keeps
 * its prefix (`16-1` looks like a version) while `9-trees` loses its own.
 * Approximating this was wrong twice; do not hand-simplify it.
 *
 * Deriving the route rather than reading Docusaurus's own route table is
 * deliberate: the manifest is generated BEFORE the build, so that table does
 * not exist yet. scripts/verify-manifest-urls.js closes the loop by comparing
 * every url against the real routes once a build has run.
 */
const IGNORED_PREFIX_PATTERN = /^\d+[-_.]\d+/;
const NUMBER_PREFIX_PATTERN = /^(\d+)\s*[-_.]+\s*([^-_.\s].*)$/;

function stripNumberPrefix(segment) {
  if (IGNORED_PREFIX_PATTERN.test(segment)) return segment;
  const match = NUMBER_PREFIX_PATTERN.exec(segment);
  return match ? match[2] : segment;
}

function routeFor(relPath, id) {
  const segments = relPath.replace(/\.mdx?$/, '').split('/');
  segments.pop(); // the file name is replaced by the frontmatter id
  return [ROUTE_BASE, ...segments.map(stripNumberPrefix), id].join('/');
}

/** DSA pages live one level deeper, so they get a group of their own. */
function locate(relPath) {
  const parts = relPath.split('/');
  if (parts.length < 2) return { group: '(root)', block: '(root)' };
  if (parts[0] === 'dsa' && parts.length > 2) {
    return { group: 'dsa', block: `dsa/${parts[1]}` };
  }
  return { group: parts[0], block: parts[0] };
}

/** DSA categories carry their label in _category_.json; other blocks do not. */
function blockLabel(block) {
  if (BLOCK_LABELS[block]) return BLOCK_LABELS[block];
  const categoryFile = path.join(docsDir, block, '_category_.json');
  if (fs.existsSync(categoryFile)) {
    try {
      const raw = fs.readFileSync(categoryFile, 'utf8').replace(/^\uFEFF/, '');
      const parsed = JSON.parse(raw.trim());
      if (parsed.label) return parsed.label;
    } catch (err) {
      // fall through to the derived label
    }
  }
  return titleCase(block.split('/').pop());
}

function generate() {
  if (!fs.existsSync(docsDir)) {
    throw new Error(`[content-manifest] docs directory not found: ${docsDir}`);
  }

  const problems = [];
  const seen = new Map();
  const pages = [];

  for (const relPath of walk(docsDir)) {
    const text = fs.readFileSync(path.join(docsDir, relPath), 'utf8');
    const fm = frontmatter(text);
    const { group, block } = locate(relPath);

    const id = fm.id;
    if (!id) {
      problems.push(`missing frontmatter id: ${relPath}`);
      continue;
    }
    if (seen.has(id)) {
      problems.push(`duplicate id "${id}": ${seen.get(id)} and ${relPath}`);
      continue;
    }
    seen.set(id, relPath);

    const difficulty = difficultyOf(fm.sidebar_class_name);
    if (!difficulty) {
      problems.push(
        `missing or unrecognised sidebar_class_name: ${relPath} ` +
          `(got ${JSON.stringify(fm.sidebar_class_name || null)})`
      );
      continue;
    }

    pages.push({
      id,
      group,
      block,
      title: fm.title || id,
      difficulty,
      points: POINTS[difficulty],
      position: Number(fm.sidebar_position) || 0,
      url: routeFor(relPath, id),
    });
  }

  if (problems.length) {
    throw new Error(
      `[content-manifest] ${problems.length} content problem(s), refusing to ` +
        `write a manifest that progress records would key on:\n  ` +
        problems.join('\n  ')
    );
  }

  pages.sort(
    (a, b) =>
      a.group.localeCompare(b.group) ||
      a.block.localeCompare(b.block) ||
      a.position - b.position ||
      a.id.localeCompare(b.id)
  );

  const tally = () => ({ pages: 0, points: 0, easy: 0, medium: 0, hard: 0 });
  const blocks = {};
  const groups = {};
  const difficulties = { easy: 0, medium: 0, hard: 0 };
  let totalPoints = 0;

  for (const page of pages) {
    blocks[page.block] = blocks[page.block] || {
      ...tally(),
      group: page.group,
      label: blockLabel(page.block),
    };
    groups[page.group] = groups[page.group] || {
      ...tally(),
      label: BLOCK_LABELS[page.group] || titleCase(page.group),
    };
    for (const bucket of [blocks[page.block], groups[page.group]]) {
      bucket.pages += 1;
      bucket.points += page.points;
      bucket[page.difficulty] += 1;
    }
    difficulties[page.difficulty] += 1;
    totalPoints += page.points;
  }

  const manifest = {
    totalPages: pages.length,
    totalPoints,
    difficulties,
    weights: POINTS,
    groups,
    blocks,
    pages,
  };

  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outFile, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  console.log(
    `[content-manifest] Generated ${outFile} ` +
      `(${pages.length} pages, ${totalPoints} points)`
  );
  return manifest;
}

generate();
module.exports = generate;
